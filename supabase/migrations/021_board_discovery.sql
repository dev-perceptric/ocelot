-- Job board discovery: Ocelot looks for companies' public job boards by itself. Each company name on the list is
-- checked once a week against every board type; a board with jobs that pass our filters is added and synced.
-- New companies on Ocelot join the list. Server only: no policies.

create table public.board_candidates (
  slug text primary key check (slug ~ '^[a-z0-9][a-z0-9._-]{0,99}$'),
  name text not null check (length(trim(name)) between 1 and 120),
  provider text check (provider in ('greenhouse', 'lever', 'ashby', 'smartrecruiters', 'recruitee', 'workable')),
  board text check (board ~ '^[A-Za-z0-9][A-Za-z0-9._-]{0,99}$'),
  checked_at timestamptz,
  source_id uuid references public.job_sources(id) on delete set null,
  skip boolean not null default false, -- a board Ocelot deleted stays deleted
  created_at timestamptz not null default now()
);
alter table public.board_candidates enable row level security;
create index board_candidates_due on public.board_candidates(checked_at nulls first) where not skip and source_id is null;

-- Names to check now: never checked first (known boards before guesses), then a week after the last check.
create or replace function public.due_candidates(p_limit int default 40, p_now timestamptz default now())
returns setof public.board_candidates
language sql stable security definer set search_path = public as $$
  select * from board_candidates
  where not skip and source_id is null and (checked_at is null or checked_at < p_now - interval '7 days')
  order by checked_at nulls first, (provider is null), slug
  limit p_limit
$$;
revoke execute on function public.due_candidates(int, timestamptz) from public, anon, authenticated;

-- A company that joins Ocelot is looked for too: its address without dashes is the usual board name.
create or replace function public.org_board_candidate() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  insert into board_candidates (slug, name) values (left(replace(new.slug, '-', ''), 100), new.name) on conflict (slug) do nothing;
  return new;
end $$;
create trigger orgs_board_candidate after insert on public.orgs for each row execute function public.org_board_candidate();

